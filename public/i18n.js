const originals = new WeakMap();
function translate(root) {
  if (
    !root ||
    root.nodeType !== 1 ||
    root.closest(
      "script,style,pre,code,.bubble,.message-body,[data-i18n-ignore]",
    )
  )
    return;
  const translateValue = (node, key, value, set) => {
    let record = originals.get(node);
    if (!record) originals.set(node, (record = {}));
    const old = record[key];
    const source = old && old.output === value ? old.source : value;
    const core = source.trim();
    const output =
      language === "en" ? source.replace(core, translateEnglish(core)) : source;
    record[key] = { source, output };
    if (output !== value) set(output);
  };
  for (const el of [root, ...root.querySelectorAll("*")]) {
    if (
      el.closest(
        "script,style,pre,code,.bubble,.message-body,[data-i18n-ignore]",
      )
    )
      continue;
    for (const node of el.childNodes)
      if (node.nodeType === 3 && el.tagName !== "TEXTAREA")
        translateValue(
          node,
          "text",
          node.nodeValue,
          (value) => (node.nodeValue = value),
        );
    for (const name of ["placeholder", "title", "aria-label"])
      if (el.hasAttribute(name))
        translateValue(el, name, el.getAttribute(name), (value) =>
          el.setAttribute(name, value),
        );
  }
}
export function setLanguage(value) {
  language = normalizeLanguage(value === "system" ? navigator.language : value);
  document.documentElement.lang = language;
  translate(document.body);
}
export function observeLanguage() {
  const observer = new MutationObserver((records) => {
    const roots = new Set();
    for (const r of records)
      roots.add(r.target.nodeType === 1 ? r.target : r.target.parentElement);
    for (const root of roots) translate(root);
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "title", "aria-label"],
  });
  translate(document.body);
  return () => observer.disconnect();
}
