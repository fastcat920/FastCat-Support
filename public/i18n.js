export function normalizeLanguage(value) {
  return /^en(?:-|$)/i.test(value || "") ? "en" : "zh-CN";
}
let language = "zh-CN";
export function translateEnglish(text) {
  if (english[text]) return english[text];
  let match;
  if (
    (match = text.match(
      /^当前工作量：(\d+)。仅在线且未满容量的成员会自动分配转人工会话。$/,
    ))
  )
    return (
      "Current workload: " +
      match[1] +
      ". Human handoffs are assigned only to online members with available capacity."
    );
  if ((match = text.match(/^(你|客服|AI 助手|系统) · ([0-9:]+)$/)))
    return english[match[1]] + " · " + match[2];
  if ((match = text.match(/^(.*) · 访客提供$/)))
    return (english[match[1]] || match[1]) + " · Provided by visitor";
  if ((match = text.match(/^版本 ([0-9.]+)$/))) return "Version " + match[1];
  if ((match = text.match(/^(\d+) 条会话$/)))
    return match[1] + " conversations";
  if ((match = text.match(/^(\d+) 位可见访客$/)))
    return match[1] + " visible customers";
  if ((match = text.match(/^(.*) · (管理员|客服)$/)))
    return match[1] + " · " + english[match[2]];
  if ((match = text.match(/^(.*) · (已读|已送达|已发送) · (.*)$/)))
    return (
      (english[match[1]] || match[1]) +
      " · " +
      english[match[2]] +
      " · " +
      match[3]
    );
  if ((match = text.match(/^选择 (.*) 的会话$/)))
    return "Select conversation: " + match[1];
  return text;
}
